async function toggleToolKey(tool) {
  const val = document.getElementById('keyVal_' + tool);
  const btn = document.getElementById('keyToggle_' + tool);
  if (!val || !btn) return;

  if (btn.dataset.shown === '1') {
    val.textContent = btn.dataset.prefix || '••••••••';
    val.style.color = 'var(--text-muted)';
    btn.textContent = t('profile_key_show');
    btn.dataset.shown = '0';
    return;
  }

  btn.disabled = true;
  try {
    const key = await fetchToolKey(tool);
    if (!key) { showToast(t('profile_key_lost'), 'error'); return; }
    btn.dataset.prefix = val.textContent;
    val.textContent = key;
    val.style.color = 'var(--primary)';
    btn.textContent = t('profile_key_hide');
    btn.dataset.shown = '1';
  } catch (e) {
    showToast(e.message || 'Error', 'error');
  } finally {
    btn.disabled = false;
  }
}

