window.submitChangeRequest = async function(platform, btn, accountId) {
  const reason = document.getElementById('changeReason')?.value;
  const details = document.getElementById('changeDetails')?.value?.trim();

  if (!reason) {
    showToast(t('profile_change_select_reason') || 'Select a reason', 'error');
    return;
  }

  btn.disabled = true;
  btn.textContent = '...';

  // Choose endpoint: slot-based (multi-account aware) when accountId present,
  // legacy platform-based when called without accountId (older UI paths).
  const endpoint = accountId ? `/api/profile/socials/${accountId}/change-request` : '/api/profile/socials/change-request';
  const body = accountId
    ? { reason, reason_details: details }
    : { platform, reason, reason_details: details };

  try {
    const res = await fetch(endpoint, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      credentials: 'same-origin',
      body: JSON.stringify(body),
    });
    const data = await res.json().catch(() => ({}));
    if (data.code === 'REQUEST_EXISTS') {
      showToast((typeof t === 'function' && t('profile_unlink_already_pending')) || 'You already have an unlink request awaiting review for this account', 'error');
      btn.disabled = false;
      btn.textContent = t('profile_unlink_request_btn') || 'Submit unlink request';
      return;
    }
    if (res.status === 429 && data.error === 'change_request_cooldown') {
      const info = unlinkEta(data.available_at);
      const dateStr = info ? `${info.exact} (${info.eta})` : '';
      const msg = (t('change_request_cooldown_error') || 'Next unlink request for {platform} available from {date}')
        .replace('{platform}', platform).replace('{date}', dateStr);
      showToast(msg, 'error');
      btn.disabled = false;
      btn.textContent = t('profile_unlink_request_btn') || 'Submit unlink request';
      return;
    }
    if (data.ok) {
      showToast(t('profile_unlink_submitted') || 'Unlink request submitted for review', 'success');
      btn.closest('div[style*=fixed]').remove();
    } else {
      showToast(data.error || 'Error', 'error');
      btn.disabled = false;
      btn.textContent = t('profile_unlink_request_btn') || 'Submit unlink request';
    }
  } catch (e) {
    showToast('Network error', 'error');
    btn.disabled = false;
    btn.textContent = t('profile_unlink_request_btn') || 'Submit unlink request';
  }
};

