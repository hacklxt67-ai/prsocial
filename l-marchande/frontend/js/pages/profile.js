// Auto-load whenever the placeholder appears in DOM. The profile page
// rerenders on language switch / data refresh — a MutationObserver re-runs
// the loader each time #tgNotifBlock shows up.
(function attachTgNotifObserver(){
  let lastSeenAt = 0;
  const tryLoad = () => {
    const el = document.getElementById('tgNotifBlock');
    if (!el) return;
    // Debounce — only one load per 500ms even if DOM mutates several times.
    const now = Date.now();
    if (now - lastSeenAt < 500) return;
    lastSeenAt = now;
    loadTgNotifications();
  };
  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', tryLoad);
  } else {
    tryLoad();
  }
  try {
    const mo = new MutationObserver(() => tryLoad());
    mo.observe(document.body, { childList: true, subtree: true });
  } catch (_) { /* old browser, skip */ }
})();


/* How long until this platform can be unlinked again.
 *
 * The cooldown runs from the exact minute of the last unlink, so "8/5/2026"
 * alone was misleading — a user who unlinked at 15:00 read the date, tried at
 * 09:00 and got refused again. Inside the last day the countdown switches to
 * hours and minutes, and the exact local timestamp is always spelled out.
 *
 * Returns null when nothing blocks the platform. */
function unlinkEta(iso) {
  if (!iso) return null;
  const end = new Date(iso).getTime();
  if (!Number.isFinite(end)) return null;
  const left = end - Date.now();
  if (left <= 0) return null;
  const mins = Math.ceil(left / 60000);
  const hours = Math.floor(mins / 60);
  const days = Math.floor(hours / 24);
  let eta;
  if (mins < 60) {
    eta = (t('profile_unlink_eta_min') || '{m} min').replace('{m}', mins);
  } else if (hours < 24) {
    // a bare "5 h" reads better than "5 h 0 min"
    eta = (mins % 60)
      ? (t('profile_unlink_eta_hm') || '{h} h {m} min').replace('{h}', hours).replace('{m}', mins % 60)
      : (t('profile_unlink_eta_h') || '{h} h').replace('{h}', hours);
  } else {
    eta = (hours % 24)
      ? (t('profile_unlink_eta_days') || '{d} d {h} h').replace('{d}', days).replace('{h}', hours % 24)
      : (t('profile_unlink_eta_d') || '{d} d').replace('{d}', days);
  }
  const d = new Date(end);
  const exact = d.toLocaleString([], {
    day: 'numeric', month: 'short', hour: '2-digit', minute: '2-digit',
  });
  return { eta, exact, left, hours };
}

