// Auto-verify via sociavault API for platforms with bio scraping support (instagram, tiktok).
// Posts {platform, account_id, username} to /socials/bio-verify; server reads the user's bio
// directly via sociavault and looks for the prs_xxxxxx code. No screenshot, no AI vision.
//
// UX codes from backend:
//   ok                       → toast + reload socials
//   API_BUSY                 → inline warning, retry in a minute, attempt NOT counted
//   PROFILE_PRIVATE_BLOCKED  → inline notice "make profile public" — TikTok-specific, NOT counted
//   AI_EXHAUSTED             → toast "manual review", reload socials
//   CODE_NOT_FOUND / PROFILE_NOT_FOUND / NO_CODE → inline red message with attempts-left
async function bioVerifySlot(platform, accountId, username) {
  const statusEl = document.getElementById('sa-verify-status-' + accountId) || document.getElementById('verify-status-' + platform);
  const platformLabel = platform === 'tiktok' ? 'TikTok' : platform === 'instagram' ? 'Instagram' : platform === 'twitter' ? 'Twitter' : platform === 'youtube' ? 'YouTube' : platform === 'facebook' ? 'Facebook' : platform === 'threads' ? 'Threads' : platform;
  if (statusEl) {
    statusEl.innerHTML = '<div style="display:flex;align-items:center;gap:8px;padding:6px 0">'
      + '<div class="spinner" style="width:14px;height:14px;border:2px solid var(--surface-2, rgba(255,255,255,0.1));border-top-color:var(--accent, #ea580c);border-radius:50%;animation:spin 0.8s linear infinite"></div>'
      + '<span style="color:var(--text-muted)">Checking your ' + platformLabel + ' bio...</span>'
      + '</div>';
  }
  try {
    const res = await fetch('/api/profile/socials/bio-verify', {
      method: 'POST', credentials: 'same-origin',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ platform, account_id: accountId, username }),
    });
    const data = await res.json();
    if (res.ok && data.ok) {
      showToast(data.message || (t('profile_verified') || 'Verified!'), 'success');
      if (statusEl) statusEl.innerHTML = '';
      await loadSocials();
      return;
    }
    if (data.code === 'API_BUSY') {
      if (statusEl) statusEl.innerHTML = '<div style="padding:8px;background:rgba(245,158,11,0.08);border:1px solid rgba(245,158,11,0.2);border-radius:8px;color:var(--text-secondary)">'
        + '<strong style="color:#f59e0b">' + (t('error_server_busy') || 'Service busy') + '</strong> '
        + (t('error_server_busy_hint') || 'Please try again in a minute. Your attempt was not counted.')
        + '</div>';
      return;
    }
    if (data.code === 'PROFILE_PRIVATE_BLOCKED') {
      if (statusEl) statusEl.innerHTML = '<div style="padding:8px;background:rgba(99,102,241,0.08);border:1px solid rgba(99,102,241,0.2);border-radius:8px;color:var(--text-secondary);line-height:1.45">'
        + '<strong style="color:#6366f1">Profile not accessible</strong><br>'
        + 'Your ' + platformLabel + ' profile is private or region-locked, so we cannot read your bio. '
        + 'Make the profile public temporarily, then click <strong>Verify</strong> again. '
        + 'Your attempt was not counted.'
        + '</div>';
      return;
    }
    // Per-criterion checklist for platforms with quality gates (TikTok, Twitter, …).
    // Renders BOTH the bio-code result AND each quality check so the user sees
    // what passed and what's missing. Backend returns code='QUALITY_FAIL' (or
    // 'AI_EXHAUSTED' on the 3rd bio attempt with checks attached). Legacy code
    // 'TIKTOK_QUALITY_FAIL' is kept for in-flight items from older deploy.
    if (data.code === 'QUALITY_FAIL' || data.code === 'TIKTOK_QUALITY_FAIL'
        || (data.code === 'AI_EXHAUSTED' && Array.isArray(data.checks) && data.checks.length)) {
      // Backfill `platform` for legacy responses that didn't include it.
      if (!data.platform) data.platform = platform;
      if (statusEl) statusEl.innerHTML = renderQualityCard(data, accountId);
      if (data.code === 'AI_EXHAUSTED') {
        showToast(t('profile_verify_manual_review') || 'Sent for manual review', 'info');
        // Give the user a moment to read the report before reloading.
        setTimeout(() => loadSocials().catch(() => {}), 4500);
      }
      return;
    }
    if (data.code === 'AI_EXHAUSTED') {
      showToast(t('profile_verify_manual_review') || 'Sent for manual review', 'info');
      await loadSocials();
      return;
    }
    // CODE_NOT_FOUND, PROFILE_NOT_FOUND, NO_CODE, etc. — show inline error with attempts-left
    const attemptsLeft = data.max_attempts ? (data.max_attempts - (data.attempts || 0)) : null;
    const attemptsText = attemptsLeft != null ? ' (' + (t('profile_verify_attempts_left') || 'attempts left') + ': ' + attemptsLeft + ')' : '';
    if (statusEl) statusEl.innerHTML = '<span style="color:var(--danger, #ef4444)">' + (data.error || 'Verification failed') + attemptsText + '</span>';
  } catch (e) {
    if (statusEl) statusEl.innerHTML = '<span style="color:var(--danger, #ef4444)">Network error</span>';
  }
}

// Render a per-criterion checklist for any platform with a quality gate.
// Backend sends `data.platform` ('tiktok' | 'twitter') + `data.checks[]`.
// Texts and label keys are shared (tt_quality_check_*); the only platform-specific
// strings are the "videos vs posts" pair (tt_quality_check_videos vs tw_quality_check_posts)
// and the failure header which interpolates the platform name.
function renderQualityCard(data, accountId) {
  const checks = Array.isArray(data.checks) ? data.checks : [];
  const username = data.username || '';
  const platform = data.platform || 'tiktok';
  const platformLabel = platform === 'tiktok' ? 'TikTok' : platform === 'twitter' ? 'Twitter' : platform === 'instagram' ? 'Instagram' : platform === 'youtube' ? 'YouTube' : platform === 'facebook' ? 'Facebook' : platform === 'threads' ? 'Threads' : platform;
  const allPass = checks.length > 0 && checks.every(c => c.pass);
  const headerColor = allPass ? '#10b981' : '#ef4444';
  const headerText = allPass
    ? (t('tt_quality_success') || 'Account meets requirements')
    : ((t('tt_quality_recheck_fail') || 'Profile does not meet {platform} requirements').replace('TikTok', platformLabel).replace('{platform}', platformLabel));
  const titleText = (t('tt_quality_title') || 'Profile check @{username}').replace('{username}', username);
  const labelKeyMap = {
    bio_code: 'tt_quality_check_bio',
    public: 'tt_quality_check_public',
    videos: 'tt_quality_check_videos',   // TikTok
    posts: 'tw_quality_check_posts',     // Twitter (Instagram overrides below)
    avatar: 'tt_quality_check_avatar',
    username_digits: 'tt_quality_check_username',
    profile_exists: 'tt_quality_check_profile',
  };

  function rowFor(c) {
    let labelKey = labelKeyMap[c.id] || c.id;
    // Instagram has a higher posts threshold (10) so it uses its own label text.
    if (c.id === 'posts' && platform === 'instagram') labelKey = 'ig_quality_check_posts';
    // YouTube uses "video or Short" wording (not just "video").
    if (c.id === 'videos' && platform === 'youtube') labelKey = 'yt_quality_check_videos';
    const label = t(labelKey) || c.id;
    let detail = '';
    let fix = '';
    if (!c.pass) {
      if (c.id === 'bio_code') {
        detail = t('tt_quality_check_bio_fail') || 'Currently: not found';
        fix = t('tt_quality_check_bio_fix') || 'Save your bio with the code, then try again';
      } else if (c.id === 'public') {
        detail = t('tt_quality_check_public_fail') || 'Currently: private';
        fix = (t('tt_quality_check_public_fix') || 'Open your profile in {platform} settings')
          .replace('TikTok', platformLabel).replace('{platform}', platformLabel);
      } else if (c.id === 'videos') {
        const n = Number(c.current) || 0;
        detail = (t('tt_quality_check_videos_now') || 'Currently: {n} videos').replace('{n}', n);
        fix = (t('tt_quality_check_videos_fix') || 'Publish {n} more').replace('{n}', Math.max(0, 1 - n));
      } else if (c.id === 'posts') {
        const n = Number(c.current) || 0;
        // Instagram threshold is 10; Twitter is 1. Same "Currently / Publish more" text wording.
        const minPosts = platform === 'instagram' ? 5 : 1;
        detail = (t('tw_quality_check_posts_now') || 'Currently: {n} posts').replace('{n}', n);
        fix = (t('tw_quality_check_posts_fix') || 'Publish {n} more').replace('{n}', Math.max(0, minPosts - n));
      } else if (c.id === 'avatar') {
        detail = t('tt_quality_check_avatar_fail') || 'Currently: missing';
        fix = t('tt_quality_check_avatar_fix') || 'Upload a profile photo';
      } else if (c.id === 'username_digits') {
        const digits = c.current || '';
        detail = (t('tt_quality_check_username_now') || 'Currently: "{digits}" inside @{username}').replace('{digits}', digits).replace('{username}', username);
        fix = t('tt_quality_check_username_fix') || 'Looks like a bot. Connect a different account';
      } else if (c.id === 'profile_exists') {
        detail = t('tt_quality_check_profile_fail') || 'Currently: profile not found';
        fix = t('tt_quality_check_profile_fix') || 'Check the username and try again';
      }
    }
    const icon = c.pass ? '✓' : '❌';
    const color = c.pass ? '#10b981' : '#ef4444';
    const detailHtml = detail ? '<div style="font-size:12px;color:var(--text-muted, #71717a);margin-top:2px">' + escHtml(detail) + '</div>' : '';
    const fixHtml = fix ? '<div style="font-size:12px;color:var(--text-secondary, #52525b);margin-top:2px">→ ' + escHtml(fix) + '</div>' : '';
    return '<div style="display:flex;gap:10px;padding:8px 0;border-bottom:1px dashed var(--border, rgba(0,0,0,0.08))">'
      + '<div style="flex:0 0 18px;color:' + color + ';font-size:14px;line-height:1.3;font-weight:700">' + icon + '</div>'
      + '<div style="flex:1;min-width:0">'
      + '<div style="font-size:13px;color:var(--text-primary, #18181b);font-weight:600">' + escHtml(label) + '</div>'
      + detailHtml + fixHtml
      + '</div></div>';
  }

  const rowsHtml = checks.map(rowFor).join('');
  let attemptsHtml = '';
  if (data.attempts != null && data.max_attempts != null) {
    const left = Math.max(0, data.max_attempts - data.attempts);
    attemptsHtml = '<div style="font-size:11px;color:var(--text-muted, #71717a);margin-top:8px">'
      + (t('profile_verify_attempts_left') || 'Attempts left') + ': ' + left + ' / ' + data.max_attempts + '</div>';
  }
  const bg = allPass ? 'rgba(16,185,129,0.06)' : 'rgba(239,68,68,0.05)';
  const border = allPass ? 'rgba(16,185,129,0.3)' : 'rgba(239,68,68,0.3)';
  return '<div style="border:1px solid ' + border + ';background:' + bg + ';border-radius:12px;padding:14px;line-height:1.45">'
    + '<div style="font-size:13px;font-weight:700;color:' + headerColor + ';margin-bottom:2px">' + escHtml(headerText) + '</div>'
    + '<div style="font-size:11px;color:var(--text-muted, #71717a);margin-bottom:8px">' + escHtml(titleText) + '</div>'
    + '<div>' + rowsHtml + '</div>'
    + attemptsHtml
    + '</div>';
}

