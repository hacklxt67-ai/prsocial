// Build profile URL from username for each platform
function buildProfileUrl(platform, username) {
  const clean = username.replace(/^@/, '').trim();
  const urlTemplates = {
    instagram: `https://www.instagram.com/${clean}/`,
    youtube: `https://www.youtube.com/@${clean}/`,
    tiktok: `https://www.tiktok.com/@${clean}/`,
    telegram: `https://t.me/${clean}/`,
    twitter: `https://x.com/${clean}/`,
    linkedin: `https://www.linkedin.com/in/${clean}/`,
    threads: `https://www.threads.net/@${clean}/`,
    snapchat: `https://www.snapchat.com/add/${clean}/`,
    reddit: `https://www.reddit.com/user/${clean}/`,
    likee: `https://likee.video/@${clean}/`,
    facebook: /^\d+$/.test(clean) ? `https://www.facebook.com/profile.php?id=${clean}` : `https://www.facebook.com/${clean}`,
    quora: `https://www.quora.com/profile/${clean}/`,
  };
  return urlTemplates[platform] || '';
}

// Extract username from URL or raw input
function extractUsernameFromInput(platform, input) {
  const val = (input || '').trim();
  if (!val) return null;

  // Try parsing as URL first
  try {
    const u = new URL(val);
    const parts = u.pathname.split('/').filter(Boolean);
    if (platform === 'linkedin' && parts.length >= 2) return parts[1];
    if (platform === 'snapchat' && parts[0] === 'add' && parts[1]) return parts[1];
    if (platform === 'reddit' && (parts[0] === 'user' || parts[0] === 'u') && parts[1]) return parts[1];
    if (platform === 'likee' && parts[0] && parts[0].startsWith('@')) return parts[0].replace('@', '');
    if (platform === 'likee' && parts[0]) return parts[0].replace('@', '');
    if (platform === 'facebook' && parts[0] === 'profile.php') { const idMatch = u.search.match(/id=(\d+)/); if (idMatch) return idMatch[1]; }
    if (platform === 'facebook' && parts[0]) return parts[0];
    if (platform === 'quora' && parts[0] === 'profile' && parts[1]) return parts[1];
    if (platform === 'youtube' && parts[0] === 'channel' && parts[1]) return parts[1];
    if (parts.length > 0) return parts[parts.length > 1 && ['in','company','add'].includes(parts[0]) ? 1 : 0].replace('@', '');
  } catch {}

  // Not a URL — treat as raw username
  return val.replace(/^@/, '').replace(/\/$/, '');
}

async function submitSocial(platform) {
  const rawInput = document.getElementById(`url-${platform}`)?.value?.trim();

  if (!rawInput) {
    showToast(t('profile_fill_all'), 'error');
    return;
  }

  // Extract username from whatever was entered (URL or plain username)
  const username = extractUsernameFromInput(platform, rawInput);
  if (!username || username.length < 2) {
    showToast(t('profile_fill_all'), 'error');
    return;
  }

  // Build proper profile URL (always send a valid URL to backend)
  const isUrl = rawInput.startsWith('http://') || rawInput.startsWith('https://');
  const profile_url = isUrl ? rawInput : buildProfileUrl(platform, username);

  if (!profile_url) {
    showToast(t('profile_fill_all'), 'error');
    return;
  }

  const btn = document.querySelector(`#form-${platform} .btn`);
  if (btn) { btn.disabled = true; btn.textContent = t('common_loading'); }

  try {
    const res = await fetch('/api/profile/socials', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      credentials: 'same-origin',
      body: JSON.stringify({ platform, username: username.replace(/^@/, ''), profile_url }),
    });
    const data = await res.json();
    if (data.ok) {
      showToast(data.message || t('profile_submitted'), 'success');
      Router.handle(); // re-render
    } else {
      showToast(data.error || 'Error', 'error');
      if (btn) { btn.disabled = false; btn.textContent = t('profile_submit'); }
    }
  } catch (e) {
    showToast('Network error', 'error');
    if (btn) { btn.disabled = false; btn.textContent = t('profile_submit'); }
  }
}

