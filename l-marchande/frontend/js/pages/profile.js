// The checks of an account are used up and a person of the staff looks at it. The site says so (manual_review in
// GET /api/profile/socials): how many checks there are, and whether a pause follows them instead of a review, is its setting.
function isManualReview(account) {
  if (!account) return false;
  return account.manual_review != null ? !!account.manual_review : (account.ai_attempts || 0) >= 3;
}

