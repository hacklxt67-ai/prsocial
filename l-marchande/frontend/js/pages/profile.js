// Reject HEIC/HEIF uploads on the client side. Sharp on the server has no
// libheif support and crashes with "bad seek" errors. Catching here avoids
// the failed upload + lets us show a helpful iPhone-specific message.
/* wcAvatarPick guard injected 2026-05-10 */
window.wcAvatarPick = function(input) {
  if (!input || !input.files || !input.files[0]) return;
  const f = input.files[0];
  const name = (f.name || '').toLowerCase();
  const type = (f.type || '').toLowerCase();
  const isHeic = name.endsWith('.heic') || name.endsWith('.heif')
    || type === 'image/heic' || type === 'image/heif'
    || type === 'image/heic-sequence' || type === 'image/heif-sequence';
  if (isHeic) {
    input.value = '';
    const msg = (typeof t === 'function' ? t('wc_avatar_heic_error') : '') ||
      'iPhone HEIC format is not supported. On iPhone: Settings → Camera → Formats → "Most Compatible" — then take a new photo, or save as JPEG before upload.';
    if (typeof showToast === 'function') showToast(msg, 'error');
    else alert(msg);
    return;
  }
  // Generic guard — anything that's not jpeg/png/webp explicitly
  if (type && !['image/jpeg','image/png','image/webp'].includes(type) && !/\.(jpe?g|png|webp)$/i.test(name)) {
    input.value = '';
    if (typeof showToast === 'function') {
      showToast((typeof t === 'function' ? t('wc_avatar_bad_format') : '') || 'Use JPEG, PNG or WebP image format.', 'error');
    }
  }
};


