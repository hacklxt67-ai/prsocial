// Multi-account aware verify. Shows progress on THIS card, reloads ONLY socials
// section on success (no full page rerender). Backend finds the pending slot
// by (user_id, platform, username, status='pending', deleted_at IS NULL) —
// which works for multi because each slot has a distinct username.
async function aiVerifyScreenshotSlot(platform, username, input, accountId) {
  const file = input.files?.[0];
  if (!file) return;
  input.value = '';
  const statusEl = document.getElementById('sa-verify-status-' + accountId) || document.getElementById('verify-status-' + platform);
  if (statusEl) {
    statusEl.innerHTML = '<div style="display:flex;align-items:center;gap:8px;padding:6px 0">'
      + '<div class="spinner" style="width:14px;height:14px;border:2px solid var(--surface-2, rgba(255,255,255,0.1));border-top-color:var(--accent, #ea580c);border-radius:50%;animation:spin 0.8s linear infinite"></div>'
      + '<span style="color:var(--text-muted)">' + (t('profile_verify_analyzing') || 'AI is analyzing your screenshot...') + '</span>'
      + '</div>';
  }
  try {
    const formData = new FormData();
    formData.append('screenshot', file);
    formData.append('platform', platform);
    formData.append('username', username);
    const res = await fetch('/api/profile/socials/verify-screenshot', {
      method: 'POST', credentials: 'same-origin', body: formData,
    });
    const data = await res.json();
    if (res.ok && data.ok) {
      showToast(data.message || (t('profile_verified') || 'Verified!'), 'success');
      // Clear this card's status, then reload the socials section
      if (statusEl) statusEl.innerHTML = '';
      await loadSocials();
      return;
    }
    // Failure paths
    if (data.code === 'API_BUSY') {
      if (statusEl) statusEl.innerHTML = '<div style="padding:8px;background:rgba(245,158,11,0.08);border:1px solid rgba(245,158,11,0.2);border-radius:8px;color:var(--text-secondary)">'
        + '<strong style="color:#f59e0b">' + (t('error_server_busy') || 'Server is busy') + '</strong> '
        + (t('error_server_busy_hint') || 'Please wait a minute and try again. Your attempt was not counted.')
        + '</div>';
    } else if (data.code === 'AI_EXHAUSTED') {
      showToast(t('profile_verify_manual_review') || 'Sent for manual review', 'info');
      await loadSocials();
      return;
    } else {
      const attemptsLeft = data.max_attempts ? (data.max_attempts - (data.attempts || 0)) : null;
      const attemptsText = attemptsLeft != null ? ' (' + (t('profile_verify_attempts_left') || 'attempts left') + ': ' + attemptsLeft + ')' : '';
      if (statusEl) statusEl.innerHTML = '<span style="color:var(--danger, #ef4444)">' + (data.error || 'AI verification failed') + attemptsText + '</span>';
    }
  } catch (e) {
    if (statusEl) statusEl.innerHTML = '<span style="color:var(--danger, #ef4444)">Network error</span>';
  }
}

// Render the full platform group — used for IG/TT/YT (multi-account capable).
// Shows existing accounts as compact rows + "Add another" button if slots remain.
// Per-platform flag: whether the inline "Add another" form is currently expanded.
// Preserved across loadSocials() re-renders.
const _addFormOpen = {};

function toggleAddForm(platformKey) {
  _addFormOpen[platformKey] = !_addFormOpen[platformKey];
  loadSocials().then(() => {
    // Auto-focus the input when the form opens
    if (_addFormOpen[platformKey]) {
      const input = document.getElementById('sa-add-input-' + platformKey);
      if (input) input.focus();
    }
  });
}

async function submitInlineAddForm(platformKey) {
  const input = document.getElementById('sa-add-input-' + platformKey);
  const btn = document.getElementById('sa-add-submit-' + platformKey);
  if (!input) return;
  const v = input.value.trim();
  if (!v) { input.focus(); return; }
  if (btn) { btn.disabled = true; btn.innerHTML = '<div class="spinner" style="width:14px;height:14px;border:2px solid rgba(255,255,255,0.25);border-top-color:#fff;border-radius:50%;animation:spin 0.8s linear infinite"></div>'; }
  try {
    await startBioVerifyFromInput(platformKey, v);
    _addFormOpen[platformKey] = false; // close form on success; new slot shows up in the list
  } catch (e) {
    // stay open on error so user can try again
  } finally {
    // state already updated by loadSocials inside startBioVerifyFromInput
    await loadSocials();
  }
}

