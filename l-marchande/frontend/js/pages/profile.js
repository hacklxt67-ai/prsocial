async function changePassword() {
  const current = document.getElementById('currentPassword')?.value;
  const newPass = document.getElementById('newPassword')?.value;
  const newPass2 = document.getElementById('newPassword2')?.value;
  const err = document.getElementById('passError');
  const btn = document.getElementById('changePassBtn');

  if (!current || !newPass) {
    if (err) { err.textContent = t('profile_fill_all'); err.classList.add('visible'); }
    return;
  }
  if (newPass.length < 6) {
    if (err) { err.textContent = t('auth_password_min'); err.classList.add('visible'); }
    return;
  }
  if (newPass !== newPass2) {
    if (err) { err.textContent = t('auth_passwords_mismatch'); err.classList.add('visible'); }
    return;
  }

  if (btn) { btn.disabled = true; btn.textContent = t('common_loading'); }
  if (err) err.classList.remove('visible');

  try {
    const res = await fetch('/api/profile/password', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      credentials: 'same-origin',
      body: JSON.stringify({ current_password: current, new_password: newPass }),
    });
    const data = await res.json();
    if (data.ok) {
      showToast(t('profile_password_changed'), 'success');
      document.getElementById('currentPassword').value = '';
      document.getElementById('newPassword').value = '';
      document.getElementById('newPassword2').value = '';
    } else {
      if (err) { err.textContent = data.error; err.classList.add('visible'); }
    }
  } catch (e) {
    if (err) { err.textContent = 'Network error'; err.classList.add('visible'); }
  } finally {
    if (btn) { btn.disabled = false; btn.textContent = t('profile_change_password_btn'); }
  }
}

