async function startBioVerifyFromInput(platformKey, input) {
  try {
    const res = await fetch('/api/profile/socials/start-verify', {
      method: 'POST',
      credentials: 'same-origin',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ platform: platformKey, username: input }),
    });
    const data = await res.json();
    if (!res.ok) { showToast(data.error || 'Error', 'error'); return; }
    if (data.already_verified) {
      showToast(t('profile_already_verified') || 'Already verified', 'info');
      return;
    }
    pendingVerifyCodes[platformKey + ':' + (data.account_id || '')] = data.code;
    showToast((t('profile_code_generated') || 'Code ready: {code}').replace('{code}', data.code), 'success');
    await loadSocials();
  } catch (e) {
    showToast('Network error', 'error');
  }
}

// A network that is no longer linked (closed: true) stands only for a person who has a linked account there;
// a link that was never finished cannot be finished now (the site refuses it: NOT_LINKABLE).
const closedShown = (p, accounts) => accounts.some(a => a.platform === p.key && a.status === 'approved');

// Reload socials section without full page reload
async function loadSocials() {
  try {
    const res = await fetch('/api/profile/socials', { credentials: 'same-origin' }).then(r => r.json());
    if (!res.ok) return;
    const grid = document.querySelector('.social-cards-grid');
    if (!grid) return;
    const accMap = {};
    (res.accounts || []).forEach(a => { if (!accMap[a.platform]) accMap[a.platform] = a; });
    const platformsMap = {};
    (res.platforms || []).forEach(g => { platformsMap[g.platform] = g; });

    grid.innerHTML = SOCIAL_PLATFORMS.filter(p => !p.closed || closedShown(p, res.accounts || [])).map(p => {
      const g = platformsMap[p.key];
      if (g && (g.is_multi || g.accounts.length > 1)) {
        return renderMultiPlatformGroup(p, g);
      }
      return renderSocialCard({ ...p, verify_provider: (platformsMap[p.key] || {}).verify_provider }, accMap[p.key]);
    }).join('');
  } catch (e) { /* ignore */ }
}

