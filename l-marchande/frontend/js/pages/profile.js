window.confirmSelfUnlink = async function(accountId, btn) {
  btn.disabled = true;
  const oldText = btn.textContent;
  btn.textContent = '...';
  try {
    const res = await fetch(`/api/profile/socials/${accountId}/self-unlink`, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      credentials: 'same-origin',
      body: '{}',
    });
    const data = await res.json().catch(() => ({}));
    if (res.status === 429 && data.error === 'change_request_cooldown') {
      const info = unlinkEta(data.available_at);
      const dateStr = info ? `${info.exact} (${info.eta})` : 'later';
      const msg = (t('profile_unlink_cooldown_error') || 'Next unlink for {platform} available from {date}')
        .replace('{platform}', data.platform || '').replace('{date}', dateStr);
      showToast(msg, 'error');
      btn.disabled = false;
      btn.textContent = oldText;
      return;
    }
    if (!res.ok || !data.ok) {
      showToast(data.error || 'Failed', 'error');
      btn.disabled = false;
      btn.textContent = oldText;
      return;
    }
    showToast(t('profile_unlink_done') || 'Account unlinked', 'success');
    btn.closest('div[style*=fixed]').remove();
    if (typeof loadProfile === 'function') loadProfile();
  } catch (e) {
    showToast('Network error', 'error');
    btn.disabled = false;
    btn.textContent = oldText;
  }
};

