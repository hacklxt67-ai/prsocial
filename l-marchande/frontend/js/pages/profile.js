// Soft-delete a linked account
async function unlinkAccount(accountId, platformName, username) {
  if (!confirm((t('profile_unlink_confirm') || 'Unlink @{username} from {platform}?')
        .replace('{username}', username).replace('{platform}', platformName))) return;
  try {
    const res = await fetch('/api/profile/socials/' + accountId + '/unlink', {
      method: 'POST',
      credentials: 'same-origin',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ reason: 'user_request' }),
    });
    const data = await res.json();
    if (!res.ok) {
      showToast(data.error || 'Error', 'error');
      return;
    }
    showToast(t('profile_unlinked') || 'Account unlinked', 'success');
    loadSocials();
  } catch (e) {
    showToast('Network error', 'error');
  }
}

