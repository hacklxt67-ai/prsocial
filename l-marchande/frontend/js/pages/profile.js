// Cancel a pending/rejected slot — deletes the record so user can add a different
// username. Approved slots cannot be self-cancelled — those use change request.
async function cancelSlotVerify(accountId, username) {
  if (!confirm((t('profile_cancel_confirm') || 'Cancel verification for @{username}? The slot will be removed and you can add a different account.').replace('{username}', username))) return;
  try {
    const res = await fetch('/api/profile/socials/cancel-verify', {
      method: 'DELETE',
      credentials: 'same-origin',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ account_id: accountId }),
    });
    const data = await res.json();
    if (!res.ok) { showToast(data.error || 'Error', 'error'); return; }
    showToast(t('profile_cancelled') || 'Cancelled', 'success');
    await loadSocials();
  } catch (e) {
    showToast('Network error', 'error');
  }
}

