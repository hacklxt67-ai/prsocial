// Change email
async function changeEmail() {
  const newEmail = document.getElementById('newEmail')?.value?.trim();
  const password = document.getElementById('emailChangePassword')?.value;
  const errEl = document.getElementById('emailError');
  const btn = document.getElementById('changeEmailBtn');

  if (errEl) errEl.textContent = '';
  if (!newEmail || !password) {
    if (errEl) errEl.textContent = t('profile_fill_all_fields') || 'Please fill all fields';
    return;
  }

  btn.disabled = true;
  btn.textContent = '...';

  try {
    const res = await API.request('POST', '/profile/email', { new_email: newEmail, password });

    if (!res.ok) {
      if (errEl) errEl.textContent = res.error || 'Error';
      return;
    }

    if (res.needs_code) {
      // Show code input for verified users
      showEmailCodeModal(newEmail);
    } else {
      // Changed immediately (unverified)
      document.getElementById('newEmail').value = '';
      document.getElementById('emailChangePassword').value = '';
      alert(t('profile_email_changed') || 'Email changed successfully!');
      location.reload();
    }
  } catch (e) {
    if (errEl) errEl.textContent = 'Network error';
  } finally {
    btn.disabled = false;
    btn.textContent = t('profile_change_email_btn') || 'Change Email';
  }
}

